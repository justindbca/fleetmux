RFC_SECRET = b'12345678901234567890'
RFC_B32 = base64.b32encode(RFC_SECRET).decode()


def invoke(argv, stdin=''):
    """(exit code, stdout, stderr) of ``cli.run``; an argparse exit counts as its code."""
    from cmux_fleet.channels import cli
    out, err = io.StringIO(), io.StringIO()
    try:
        code = cli.run(argv, stdin=io.StringIO(stdin), stdout=out, stderr=err)
    except SystemExit as exc:
        code = exc.code
    return code, out.getvalue(), err.getvalue()


def write_totp(secret_b32=RFC_B32):
    path = channels.config_dir() / 'totp.env'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('TOTP_SECRET=' + secret_b32 + '\n', encoding='utf-8')
    path.chmod(0o600)
    return path


def second_account():
    path = channels.account_path('fake2', 'contract-2')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('ALLOW=u-1\n', encoding='utf-8')
    path.chmod(0o600)
    return path


def high_record(rr, mode):
    seed_agent(rr)
    res = reg(rr, tier='high', cls='real_money', oob_modes=mode)
    _, nonce = first_step(rr, res.p_id)
    return record(rr, res.p_id), nonce


def run_cfg(tmp_path, rr, *, socket=None):
    run = tmp_path / 'run'
    run.mkdir(exist_ok=True)
    cfg = {'run': str(run), 'redis_socket': socket or rr.connection_pool.connection_kwargs['path'],
           'security': POLICY, 'channels': [{'type': 'fake', 'account': 'contract-1'}]}
    path = run / 'config.json'
    path.write_text(json.dumps(cfg))
    return str(path)


