def test_desk_mode_refuses_any_channel_second_step_accepts_cli(r, tmp_path):
    assert security.parse_security('')[0]['confirm']['high'] == 'desk'
    rec, nonce = high_record(r, 'desk')
    for ch, acct in (('fake', 'contract-1'), ('fake2', 'contract-2')):
        ok, why = oob.check(rec, ev_for(rec, nonce, channel=ch, account=acct), POLICY, r=r)
        assert ok is False and why
    for proof in (None, 'deadbeef', '0' * 64):                     # the literal 'desk' channel is not trusted
        ev = ev_for(rec, nonce, channel='desk', account='desk')
        if proof:
            ev['desk_proof'] = proof
        assert oob.check(rec, ev, POLICY, r=r)[0] is False
    key = approve.desk_key()
    path = channels.config_dir() / 'desk.key'
    assert key and stat.S_IMODE(os.stat(path).st_mode) == 0o600
    code, out, err = invoke(['channel', 'approve', '--config', run_cfg(tmp_path, r), rec['id'], nonce])
    assert code == 0 and ticket_keys(r)
    assert nonce not in out + err
    # X3: the record's oob_modes decides; later policy changes do not
    rec_t, nonce_t = high_record(r, 'totp')
    code, _, _ = invoke(['channel', 'approve', '--config', run_cfg(tmp_path, r), rec_t['id'], nonce_t])
    assert code == 1
    res_n = reg(r, action_text='normal')
    assert invoke(['channel', 'approve', '--config', run_cfg(tmp_path, r), res_n.p_id, 'f' * 16])[0] == 1
    rec2, nonce2 = high_record(r, 'desk')                         # registered and confirmed before the stop
    r.hincrby('fx:service', 'stop_epoch', 1)
    assert invoke(['channel', 'approve', '--config', run_cfg(tmp_path, r), rec2['id'], nonce2])[0] == 1


def test_second_channel_requires_different_type_account_and_whitelisted_sender(r):
    second_account()
    rec, nonce = high_record(r, 'second_channel')
    pol = policy_with(high='second_channel')
    assert oob.check(rec, ev_for(rec, nonce), pol, r=r)[0] is False                       # same type:account
    assert oob.check(rec, ev_for(rec, nonce, channel='fake2', account='contract-2', sender='u-9'), pol, r=r)[0] \
        is False                                                                             # not in its ALLOW
    for flag in ('private', 'verified'):
        ev = ev_for(rec, nonce, channel='fake2', account='contract-2')
        ev[flag] = False
        assert oob.check(rec, ev, pol, r=r)[0] is False
    assert oob.check(rec, ev_for(rec, nonce, channel='fake2', account='contract-2'), pol, r=r) == (True, '')


@pytest.mark.parametrize('t,code', [(59, '287082'), (1111111109, '081804')])      # RFC 6238 B, SHA-1, last 6
def test_totp_rfc6238_vectors_and_window_pm1(r, t, code):
    write_totp()
    rec, nonce = high_record(r, 'totp')
    pol = policy_with(high='totp')
    assert oob.check(rec, ev_for(rec, nonce, code=code), pol, r=r, now=t) == (True, '')
    r.delete(*r.scan_iter(channels.TOTP_USED + '*'))
    assert oob.check(rec, ev_for(rec, nonce, code=code), pol, r=r, now=t + 30)[0] is True       # +1 step
    r.delete(*r.scan_iter(channels.TOTP_USED + '*'))
    assert oob.check(rec, ev_for(rec, nonce, code=code), pol, r=r, now=t + 60)[0] is False      # +2 steps
    for other in ({'sender': 'u-2'}, {'conversation': 'c-2'}):
        assert oob.check(rec, ev_for(rec, nonce, code=code, **other), pol, r=r, now=t)[0] is False


def test_totp_code_single_use_within_90s(r):
    write_totp()
    rec, nonce = high_record(r, 'totp')
    pol = policy_with(high='totp')
    assert oob.check(rec, ev_for(rec, nonce, code='287082'), pol, r=r, now=59)[0] is True
    assert oob.check(rec, ev_for(rec, nonce, code='287082'), pol, r=r, now=59)[0] is False
    assert 0 < r.ttl(channels.TOTP_USED + '287082') <= 90


def test_login_totp_writes_0600_secret_prints_otpauth_once_never_again(r):
    code, out, err = invoke(['channel', 'login', 'totp'])
    path = channels.config_dir() / 'totp.env'
    assert code == 0 and out.count('otpauth://') == 1
    assert stat.S_IMODE(os.stat(path).st_mode) == 0o600
    assert stat.S_IMODE(os.stat(channels.config_dir()).st_mode) == 0o700
    secret = path.read_text(encoding='utf-8')
    code2, out2, err2 = invoke(['channel', 'login', 'totp'])
    assert 'otpauth://' not in out2 + err2 and path.read_text(encoding='utf-8') == secret
    value = secret.split('=', 1)[1].strip()
    assert value and value not in err + out2 + err2


def test_approve_cli_without_redis_fails_with_exit_1_no_secret_in_stderr(r, tmp_path):
    write_totp()
